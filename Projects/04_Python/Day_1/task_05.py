# Task 4 - Type Casting

age = "20"
semester = "3"
attendance = "95.5"

age = int(age)
semester = int(semester)
attendance = float(attendance)

print("Age:", age)
print("Age Type:", type(age))

print("Semester:", semester)
print("Semester Type:", type(semester))

print("Attendance:", attendance)
print("Attendance Type:", type(attendance))